/* ── Interpolation ────────────────────────────────────────────────────────────
   Every count string in this dictionary is a TEMPLATE with named placeholders
   (`{count}`), not a preformatted number. Rendering one without substituting
   its variables is what produced the literal `{count} courses` on screen: the
   context's `t` was typed `(key) => string`, so callers passing a second
   argument type-checked (TypeScript accepts a function with fewer parameters)
   while the value was silently dropped.

   The substitution therefore lives HERE, in the one function every caller goes
   through, rather than in per-component `.replace()` calls that each new screen
   would have to remember to add.
   ────────────────────────────────────────────────────────────────────────── */

export type DesktopI18nVars = Record<string, string | number>

/** `{name}` — a leading digit is excluded so CSS-ish braces are never eaten. */
const PLACEHOLDER = /\{([A-Za-z_][A-Za-z0-9_]*)\}/g

/**
 * Substitute `{name}` tokens.
 *
 * An unknown token is left EXACTLY as written rather than replaced with an
 * empty string: a visible `{count}` is a bug the QA scan below catches, whereas
 * a silent blank reads as a legitimately empty label.
 */
export function interpolate(template: string, vars?: DesktopI18nVars): string {
  if (!vars) return template
  return template.replace(PLACEHOLDER, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole,
  )
}

/** Every `{token}` still present in a rendered string. Empty means resolved. */
export function unresolvedPlaceholders(text: string): string[] {
  return [...text.matchAll(PLACEHOLDER)].map((match) => match[0])
}

export function translateDesktop(
  locale: ContentLanguageCode,
  key: DesktopI18nKey,
  vars?: DesktopI18nVars,
): string {
  const template = dictionaries[locale]?.[key] ?? en[key] ?? key
  return interpolate(template, vars)
}

/** Every locale this dictionary serves. Used by the placeholder QA test. */
export const DESKTOP_I18N_LOCALES = Object.keys(dictionaries) as ContentLanguageCode[]

export function desktopDictionaryKeys(locale: ContentLanguageCode): string[] {
  return Object.keys(dictionaries[locale]).sort()
}
